"use client";

// The match client store (§17.6): a tiny external store consumed with `useSyncExternalStore` + selectors, so a
// change in one field (timer offset, connection) re-renders only the components that read it. Polls answered with
// `{ same: true }` change nothing here, so they cause no re-render at all.
import { useSyncExternalStore } from "react";
import type { ClientCommand } from "../server/commands";
import { t } from "../i18n";
import type { MatchView } from "../server/view";
import { toBoardModel, type BoardModel } from "./boardModel";
import type { ConnStatus, MatchTransport, TransportUpdate } from "./transport";

export interface PendingCommand {
  /** Generated by the transport (HTTP); null for the local sandbox. */
  commandId: string | null;
  command: ClientCommand; // game or lobby command (Phase 11)
  startedAt: number;
}

export interface ToastMessage {
  id: number;
  text: string;
  /** "info" for neutral notices ("¡Enlace copiado!"); errors otherwise. */
  tone?: "info";
}

export interface MatchClientState {
  view: MatchView | null;
  board: BoardModel | null;
  pending: PendingCommand | null; // at most ONE in-flight game command
  status: ConnStatus;
  error: ToastMessage | null; // last rejection (Spanish), shown as a toast; `id` changes on every new error
  fatal: string | null; // 403/404 → leave match
  clockOffsetMs: number; // serverNow − Date.now()
  foeOnline: boolean;
}

/** Offsets that differ by less than this are not worth a re-render. */
const OFFSET_EPSILON_MS = 500;

function offsetFrom(serverNow: string | undefined): number | null {
  if (!serverNow) return null;
  const t0 = Date.parse(serverNow);
  return Number.isFinite(t0) ? t0 - Date.now() : null;
}

export class MatchClient {
  private state: MatchClientState = {
    view: null,
    board: null,
    pending: null,
    status: "connecting",
    error: null,
    fatal: null,
    clockOffsetMs: 0,
    foeOnline: false,
  };
  private readonly listeners = new Set<() => void>();
  private errorSeq = 0;
  private started = false;

  constructor(private readonly transport: MatchTransport) {}

  start(): void {
    if (this.started) return;
    this.started = true;
    this.transport.start((u) => this.onUpdate(u));
  }

  stop(): void {
    if (!this.started) return;
    this.started = false;
    this.transport.stop();
  }

  subscribe = (listener: () => void): (() => void) => {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  };

  getSnapshot = (): MatchClientState => this.state;

  private set(patch: Partial<MatchClientState>): void {
    this.state = { ...this.state, ...patch };
    for (const l of this.listeners) l();
  }

  /** Shows a Spanish message as a toast (also used by the UI for interaction hints). */
  showError(text: string): void {
    this.errorSeq += 1;
    this.set({ error: { id: this.errorSeq, text } });
  }

  /** Shows a neutral notice in the same toast slot. */
  showInfo(text: string): void {
    this.errorSeq += 1;
    this.set({ error: { id: this.errorSeq, text, tone: "info" } });
  }

  /** Seeds the store with a view the caller already has (create/join answers), so the screen paints at once. */
  prime(view: MatchView): void {
    this.onUpdate({ view, serverNow: view.serverNow });
  }

  private acceptView(view: MatchView, patch: Partial<MatchClientState>): void {
    const cur = this.state.view;
    // Version monotonicity (§13.5); a different seat/match (sandbox viewer switch) always replaces the view.
    const newer = !cur || cur.matchId !== view.matchId || cur.seat !== view.seat || view.version > cur.version;
    if (!newer) return;
    patch.view = view;
    patch.board = toBoardModel(view);
    if (view.foeOnline !== this.state.foeOnline) patch.foeOnline = view.foeOnline;
  }

  private onUpdate(u: TransportUpdate): void {
    const patch: Partial<MatchClientState> = {};
    if (u.view) this.acceptView(u.view, patch);
    if (u.status && u.status !== this.state.status) patch.status = u.status;
    if (u.fatal && u.fatal !== this.state.fatal) patch.fatal = u.fatal;
    if (u.foeOnline !== undefined && u.foeOnline !== this.state.foeOnline) patch.foeOnline = u.foeOnline;
    const offset = offsetFrom(u.serverNow ?? u.view?.serverNow);
    if (offset !== null && Math.abs(offset - this.state.clockOffsetMs) > OFFSET_EPSILON_MS) patch.clockOffsetMs = offset;
    if (Object.keys(patch).length > 0) this.set(patch);
  }

  /**
   * Sends a game or lobby command. Only one may be in flight: while `pending` is set, further commands are ignored and
   * `false` is returned. On rejection the view is unchanged (the UI reverts) and `error` is set.
   */
  async send(command: ClientCommand): Promise<boolean> {
    if (this.state.pending) return false;
    this.set({ pending: { commandId: null, command, startedAt: Date.now() } });
    const result = await this.transport.send(command);
    const patch: Partial<MatchClientState> = { pending: null };
    if (result.ok) this.acceptView(result.view, patch);
    this.set(patch);
    if (!result.ok) this.showError(result.error || t("match.noConnection"));
    return result.ok;
  }
}

/** Subscribes a component to one slice of the store. The selector must return a stable value (a field, a primitive). */
export function useMatchSelector<T>(client: MatchClient, selector: (s: MatchClientState) => T): T {
  return useSyncExternalStore(
    client.subscribe,
    () => selector(client.getSnapshot()),
    () => selector(client.getSnapshot()),
  );
}
